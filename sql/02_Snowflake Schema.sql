-- BOOKINGFACT
DROP TABLE BOOKINGFACT CASCADE CONSTRAINTS PURGE;
CREATE TABLE BOOKINGFACT AS
SELECT BT.REGISTRATIONNO, BT.FACULTYID, TO_CHAR(BOOKINGDATE, 'YYYYMM') AS TIMEID, BT.AGEID AS AGEID, COUNT(*) AS NUM_OF_BOOKING
FROM BOOKINGTEMPFACT BT 
JOIN BOOKING B ON BT.BOOKINGID = B.BOOKINGID
GROUP BY BT.REGISTRATIONNO, BT.FACULTYID, TO_CHAR(BOOKINGDATE, 'YYYYMM'), BT.AGEID;

SELECT * FROM BOOKINGFACT;


-- MAINTENANCEFACT
DROP TABLE MAINTENANCEFACT CASCADE CONSTRAINTS PURGE;
CREATE TABLE MAINTENANCEFACT AS
SELECT REGISTRATIONNO, MAINTENANCETYPE, TEAMID, COUNT(*) AS NUM_OF_MAINTENANCE, SUM(MAINTENANCECOST) AS TOTAL_MAINTENANCE_COST
FROM MAINTENANCE
GROUP BY REGISTRATIONNO, MAINTENANCETYPE, TEAMID;

SELECT * FROM MAINTENANCEFACT;


-- ACCIDENTFACT
DROP TABLE ACCIDENTFACT CASCADE CONSTRAINTS PURGE;
CREATE TABLE ACCIDENTFACT AS
SELECT CA.REGISTRATIONNO, AI.ERRORCODE, AI.ACCIDENTZONE, AI.CAR_DAMAGE_SEVERITY AS DAMAGESEVERITY, COUNT(*) AS NUM_OF_ACCIDENT
FROM MONCITY.CARACCIDENT CA
JOIN ACCIDENTINFO AI ON CA.ACCIDENTID = AI.ACCIDENTID
GROUP BY CA.REGISTRATIONNO, AI.ERRORCODE, AI.ACCIDENTZONE, AI.CAR_DAMAGE_SEVERITY;

SELECT * FROM ACCIDENTFACT;