-- MAINTENANCETEAMDIM
DROP TABLE MAINTENANCETEAMDIM CASCADE CONSTRAINTS PURGE;
CREATE TABLE MAINTENANCETEAMDIM AS
SELECT MT.TEAMID, MT.TEAMLEADER, MT.PHONE, 
    ROUND(1/COUNT(B.CENTERID),2) AS WEIGHTFACTOR, -- WEIGHT FACTOR FOR EACH TEAM
    LISTAGG(B.CENTERID, '-') WITHIN GROUP (ORDER BY B.CENTERID) AS RESEARCHCENTERLIST -- A LIST OF RESEARCH CENTER FOR EACH TEAM
FROM MONCITY.MAINTENANCETEAM MT
JOIN MONCITY.BELONGTO B ON MT.TEAMID = B.TEAMID
GROUP BY MT.TEAMID, MT.TEAMLEADER, MT.PHONE;

SELECT * FROM MAINTENANCETEAMDIM;


