-- BOOKINGTEMPFACT
DROP TABLE BOOKINGTEMPFACT CASCADE CONSTRAINTS PURGE;
CREATE TABLE BOOKINGTEMPFACT AS
SELECT B.BOOKINGID, C.REGISTRATIONNO, P.FACULTYID, P.PASSENGERAGE
FROM BOOKING B
JOIN MONCITY.CAR C ON B.REGISTRATIONNO = C.REGISTRATIONNO
JOIN PASSENGER P ON B.PASSENGERID = P.PASSENGERID;

SELECT * FROM BOOKINGTEMPFACT;


