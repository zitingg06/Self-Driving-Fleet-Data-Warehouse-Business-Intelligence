    -- METRIC 10: DEMAND IDENTFY THE PERIOD OF HIGH DEMAND IN BOOKING THE SELF-DRIVING CAR.
    SELECT 
    COALESCE(B.MONTH, M.MONTH) AS MONTH,
    NVL(B.TOTALBOOKINGS, 0) AS TOTALBOOKINGS,
    NVL(M.TOTALMAINTENANCEEVENTS, 0) AS TOTALMAINTENANCEEVENTS

    FROM 
        (SELECT T.MONTH, SUM(BF.NUM_OF_BOOKING) AS TOTALBOOKINGS
        FROM BOOKINGFACT BF
        JOIN BOOKINGTIMEDIM T ON BF.TIMEID = T.TIMEID
        GROUP BY T.MONTH) B

    JOIN 
        (SELECT TO_CHAR(MN.MAINTENANCEDATE, 'MM') AS MONTH,
                COUNT(*) AS TOTALMAINTENANCEEVENTS
        FROM MONCITY.MAINTENANCE MN
        GROUP BY TO_CHAR(MN.MAINTENANCEDATE, 'MM')) M
    ON B.MONTH = M.MONTH

    ORDER BY MONTH;




/* ======================================== FURTHER ANALYSIS SECTION 4: Team Efficiency Analysis ======================================== */

    -- METRIC 11: Maintenance Cost by Research Center TO SHOW how research centers share maintenance workloads efficiently without double-counting expenses 
    SELECT RC.CenterID, RC.CenterName,
        -- Proportional Cost Allocation
        ROUND(SUM(MF.TOTAL_MAINTENANCE_COST * MT.WEIGHTFACTOR), 2) AS Allocated_Maintenance_Cost
    FROM MAINTENANCEFACT MF
    JOIN MAINTENANCETEAMDIM MT ON MF.TEAMID = MT.TEAMID
    JOIN BRIDGETABLEDIM BD ON MT.TEAMID = BD.TEAMID
    JOIN RESEARCHCENTERDIM RC ON BD.CENTERID = RC.CENTERID
    GROUP BY RC.CenterID, RC.CenterName
    ORDER BY Allocated_Maintenance_Cost DESC;